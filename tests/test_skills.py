def test_index_all_locations_and_flags(hub):
    root, env, call = hub
    home = Path(env["USERPROFILE"])
    make_skill(root / "skills/portable", "portable", "No external dependencies.")
    (root / "skills/portable/LICENSE").write_text("Fixture licence", encoding="utf-8")
    locations = [
        (root / ".claude/skills/project-claude", "project-claude"),
        (root / ".agents/skills/project-codex", "project-codex"),
        (root / ".codex/skills/project-alt", "project-alt"),
        (home / ".claude/skills/user-claude", "user-claude"),
        (home / ".codex/skills/.system/user-codex", "user-codex"),
        (home / ".agents/skills/user-shared", "user-shared"),
        (home / ".claude/plugins/cache/vendor/plugin/1/skills/plugin-claude", "plugin-claude"),
        (home / ".codex/plugins/cache/vendor/plugin/2/skills/plugin-codex", "plugin-codex"),
    ]
    for path, name in locations:
        make_skill(path, name, "Requires MCP server. Requires python CLI. Uses $FIXTURE_TOKEN.")
    output = call("skills")
    assert "Skills: 9 (claude: 3, codex: 5, both: 1)" in output
    assert str(root / "work/skills-index.md") in output
    index = (root / "work/skills-index.md").read_text(encoding="utf-8")
    for _, name in locations:
        assert f"| {name} |" in index
    assert "| portable | both |" in index and "LICENSE (check terms)" in index
    for flag in ("MCP server", "external command", "env var"):
        assert "check: " + flag in index
    assert "unknown" in index and "check compatibility" in index
    assert "check: ok" not in index


def test_install_local_copy_excludes_pin_and_sync(hub, local_source):
    root, _, call = hub
    source, revision = local_source
    output = call("skills", "install")
    assert "UNSUPPORTED: unsupported - Use hub.py delegate instead." in output
    targets = [root / folder / "focus" for folder in (".claude/skills", ".agents/skills")]
    for target in targets:
        assert not target.is_symlink()
        assert (target / "reference.txt").read_text() == "Reference data"
        assert json.loads((target / ".hub-local").read_text())["ref"] == revision
        run_git(root, "check-ignore", str(target / "SKILL.md"))
    exclude = root / ".git/info/exclude"
    before = exclude.read_text()
    assert "/.claude/skills/focus/" in before and "/.agents/skills/focus/" in before
    (source / "skills/focus/SKILL.md").write_text("Changed upstream", encoding="utf-8")
    run_git(source, "add", "skills/focus/SKILL.md")
    run_git(source, "commit", "-m", "New upstream revision")
    for target in targets:
        (target / "stale.txt").write_text("Old install")
    call("skills", "install")  # fetches, but keeps the manifest's pinned revision
    assert exclude.read_text() == before
    for target in targets:
        assert "Pinned skill" in (target / "SKILL.md").read_text()
        assert not (target / "stale.txt").exists()
    call("sync")
    check = call("sync", "--check")
    assert check.count("LOCAL SKILL:") == 2
    assert all((target / "SKILL.md").exists() for target in targets)
    call("skills")
    index = (root / "work/skills-index.md").read_text()
    assert "fixture-cli" in index and "unknown; local only" in index
    assert "| unsupported | none |" in index and "Use hub.py delegate instead." in index


