def test_skill_install_verifies_checked_out_sha(hub, local_source, monkeypatch, capsys):
    import hub_skills
    root, _, _ = hub
    original = hub_skills.git

    def mismatched_head(*args, **kwargs):
        return "0" * 40 if args == ("rev-parse", "HEAD") else original(*args, **kwargs)

    monkeypatch.setattr(hub_skills, "git", mismatched_head)
    assert hub_skills.install_skills(root) == 1
    assert "FAILED: focus - checked-out SHA does not match source ref" in capsys.readouterr().out
    assert not (root / ".claude/skills/focus").exists()


def test_skill_install_stages_in_ignored_hub_directory(hub, local_source, monkeypatch):
    import hub_skills
    root, _, _ = hub
    original = hub_skills.tempfile.TemporaryDirectory
    directories = []

    def staging_directory(*args, **kwargs):
        assert kwargs["dir"] == root / ".hub/staging"
        temporary = original(*args, **kwargs)
        path = Path(temporary.name)
        assert path.is_relative_to(root / ".hub/staging")
        run_git(root, "check-ignore", str(path))
        directories.append(path)
        return temporary

    monkeypatch.setattr(hub_skills.tempfile, "TemporaryDirectory", staging_directory)
    assert hub_skills.install_skills(root) == 0
    assert len(directories) == 2 and all(not path.exists() for path in directories)


def test_skill_install_reports_git_ownership_failure(hub, local_source, monkeypatch, capsys):
    import hub_skills
    root, _, _ = hub
    original = hub_skills.git

    def ownership_failure(*args, **kwargs):
        if "info/exclude" in args:
            assert args == ("rev-parse", "--git-path", "info/exclude")
            raise ValueError("git failed: dubious ownership (fixture)")
        return original(*args, **kwargs)

    monkeypatch.setattr(hub_skills, "git", ownership_failure)
    assert hub_skills.install_skills(root) == 1
    assert "FAILED: focus - git failed: dubious ownership (fixture)" in capsys.readouterr().out
    assert not (root / ".claude/skills/focus").exists()


