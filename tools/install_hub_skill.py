"""Install the owned portable Hub skill without changing CLI configuration."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import tempfile
import uuid


ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills/multi-agent-hub"
FILES = ("SKILL.md", "references/brief.md", "scripts/run.py")
RUNTIME = {"hub.py": ROOT / "tools/hub.py", "hub_skills.py": ROOT / "tools/hub_skills.py",
           "models.toml": ROOT / "models.toml"}
MARKER = ".multi-agent-hub-managed.json"
SHELLS = ("hub-readonly", "hub-writer")  # bundled as sources; installed as native agents only with --claude
COMPONENT = ROOT / "skills/software-component"
SYNC_MARKER = "GENERATED by tools/hub.py sync from "


def digest_bytes(data):
    return hashlib.sha256(data).hexdigest()


def bundle():
    """Relative bundle path -> source file for everything the managed skill contains."""
    files = {name: SKILL / name for name in FILES}
    files.update({"runtime/" + name: path for name, path in RUNTIME.items()})
    files.update({f"agents/{name}.md": ROOT / "agents/shells" / (name + ".md") for name in SHELLS})
    for path in sorted(COMPONENT.rglob("*")):
        if path.is_symlink():
            raise ValueError("refusing symlink source: " + str(path))
        if path.is_file():
            files["skills/software-component/" + path.relative_to(COMPONENT).as_posix()] = path
    return files


def read_source(source):
    if any(part.is_symlink() for part in (source, *source.parents) if part != ROOT.parent) or not source.is_file():
        raise ValueError("refusing symlink or missing source: " + str(source))
    if not source.resolve().is_relative_to(ROOT.resolve()):
        raise ValueError("source escapes repository: " + str(source))
    return source.read_bytes()


def validate_existing(destination):
    marker = destination / MARKER
    if marker.is_symlink() or not marker.is_file():
        raise ValueError("refusing unmanaged destination: " + str(destination))
    try:
        old = json.loads(marker.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError("invalid managed provenance") from exc
    if not isinstance(old, dict) or old.get("format") != 1 or old.get("source") != "multi-agent-hub" or not isinstance(old.get("files"), dict):
        raise ValueError("invalid managed provenance format")
    # The recorded list (not today's bundle) defines what is managed, so an older, smaller bundle can still be updated.
    expected = set(old["files"])
    if (not expected or MARKER in expected
            or any(Path(name).is_absolute() or ".." in Path(name).parts or "\\" in name for name in expected)
            or any(not isinstance(value, str) or not re.fullmatch(r"[0-9a-f]{64}", value) for value in old["files"].values())):
        raise ValueError("managed provenance file list is invalid")
    for relative, expected_hash in old["files"].items():
        path = destination / relative
        if Path(relative).is_absolute() or not path.resolve().is_relative_to(destination.resolve()):
            raise ValueError("invalid managed file path")
        if path.is_symlink() or not path.is_file() or digest_bytes(path.read_bytes()) != expected_hash:
            raise ValueError("managed file was modified; refusing update: " + relative)
    allowed = expected | {MARKER}
    actual = set()
    for path in destination.rglob("*"):
        if path.is_symlink():
            raise ValueError("refusing symlink destination entry: " + str(path.relative_to(destination)))
        if path.is_file():
            actual.add(path.relative_to(destination).as_posix())
    if actual != allowed:
        raise ValueError("managed destination contains unexpected or missing content")
    allowed_dirs = set()
    for name in allowed:
        allowed_dirs.update(parent.as_posix() for parent in Path(name).parents if parent.as_posix() != ".")
    actual_dirs = {path.relative_to(destination).as_posix() for path in destination.rglob("*") if path.is_dir()}
    if actual_dirs != allowed_dirs:
        raise ValueError("managed destination contains unexpected directories")


def install(destination):
    destination = Path(os.path.abspath(destination.expanduser()))
    for parent in (destination, *destination.parents):
        if parent.is_symlink():
            raise ValueError("refusing symlink install path: " + str(parent))
    sources = bundle()
    hashes = {name: digest_bytes(read_source(source)) for name, source in sources.items()}
    if destination.exists():
        validate_existing(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    stage_root = Path(tempfile.mkdtemp(prefix=".mah-install-", dir=destination.parent))
    staged = stage_root / destination.name
    try:
        for relative, source in sources.items():
            target = staged / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(read_source(source))
        (staged / MARKER).write_text(json.dumps({"format": 1, "source": "multi-agent-hub", "files": hashes}, indent=2) + "\n", encoding="utf-8")
        backup = None
        if destination.exists():
            backup_root = destination.parent.parent / ".multi-agent-hub-backups"
            backup_root.mkdir(parents=True, exist_ok=True)
            backup = backup_root / (destination.name + "-" + uuid.uuid4().hex)
            destination.rename(backup)
        try:
            staged.rename(destination)
        except OSError as replacement_error:
            if backup is not None and backup.exists() and not destination.exists():
                try:
                    shutil.copytree(backup, destination)
                except OSError as restore_error:
                    raise OSError(f"replacement failed ({replacement_error}); old managed skill remains at {backup}; restore failed ({restore_error})") from replacement_error
            elif backup is None and not destination.exists():
                # First install has no active bundle to restore. A copy fallback
                # is safe only while the destination is still absent.
                shutil.copytree(staged, destination)
                return print(destination)
            raise
    finally:
        shutil.rmtree(stage_root, ignore_errors=True)
    print(destination)


def shell_parts(name):
    relative = f"agents/shells/{name}.md"
    text = read_source(ROOT / relative).decode("utf-8").replace("\r\n", "\n")
    match = re.match(r"\A---\s*\n(.*?)\n---[^\n]*\n?(.*)\Z", text, re.S)
    if not match:
        raise ValueError("missing frontmatter: " + relative)
    meta = {}
    for line in match[1].splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip()] = value.strip().strip("\"'")
    return meta, match[2].rstrip() + "\n", SYNC_MARKER + relative + "; edit the source"


def claude_agent_files():
    """Native Claude Code definitions of the permission shells, byte-identical to `hub.py sync` output."""
    files = {}
    for name in SHELLS:
        meta, body, marker = shell_parts(name)
        front = "---\nname: " + json.dumps(meta["name"]) + "\ndescription: " + json.dumps(meta["description"])
        if meta.get("tools"):
            front += "\ntools: " + meta["tools"]
        files[name + ".md"] = (front + "\n---\n<!-- " + marker + " -->\n" + body).encode()
    return files


def codex_agent_files():
    """Native Codex definitions of the permission shells, byte-identical to `hub.py sync` output."""
    files = {}
    for name in SHELLS:
        meta, body, marker = shell_parts(name)
        sandbox = meta.get("sandbox", "read-only")
        if sandbox not in ("read-only", "workspace-write"):
            raise ValueError("invalid sandbox")
        if "'''" in body:
            raise ValueError("TOML literal delimiter in shell body")
        files[name + ".toml"] = ("# " + marker + "\nname = " + json.dumps(meta["name"]) + "\ndescription = " + json.dumps(meta["description"])
                                 + "\nsandbox_mode = " + json.dumps(sandbox) + "\ndeveloper_instructions = '''\n" + body + "'''\n").encode()
    return files


def check_agents(agents_dir, files):
    """Refuse before any write: unmanaged or locally modified files with the same names are never replaced."""
    for parent in (agents_dir, *agents_dir.parents):
        if parent.is_symlink():
            raise ValueError("refusing symlink install path: " + str(parent))
    managed = {}
    marker = agents_dir / MARKER
    if marker.is_symlink() or marker.exists():
        try:
            old = json.loads(marker.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise ValueError("invalid managed agent provenance") from exc
        if (marker.is_symlink() or not isinstance(old, dict) or old.get("format") != 1
                or old.get("source") != "multi-agent-hub" or not isinstance(old.get("files"), dict)):
            raise ValueError("invalid managed agent provenance format")
        managed = old["files"]
    for name in files:
        target = agents_dir / name
        if target.is_symlink():
            raise ValueError("refusing symlink agent file: " + str(target))
        if target.exists():
            if name not in managed:
                raise ValueError("refusing unmanaged agent file: " + str(target))
            if digest_bytes(target.read_bytes()) != managed[name]:
                raise ValueError("managed agent file was modified; refusing update: " + name)
    return {name: value for name, value in managed.items() if name in files}  # only the expected keys stay managed


check_claude_agents = check_agents


def write_atomic(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=".multi-agent-hub-")
    try:
        with os.fdopen(handle, "wb") as stream:
            stream.write(data)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def write_agents(agents_dir, files):
    """Write each file, then record exactly its hash at once, so a mid-way failure never strands an unmanaged file."""
    managed = check_agents(agents_dir, files)  # refuse before touching anything
    for name, data in files.items():
        target = agents_dir / name
        previous = target.read_bytes() if target.is_file() else None
        write_atomic(target, data)
        managed[name] = digest_bytes(data)
        marker = {"format": 1, "source": "multi-agent-hub", "files": managed}
        try:
            write_atomic(agents_dir / MARKER, (json.dumps(marker, indent=2) + "\n").encode())
        except BaseException:
            # The new hash was not recorded: put the old, still-recorded file back (or remove a first-time one).
            if previous is None:
                target.unlink(missing_ok=True)
            else:
                write_atomic(target, previous)
            raise
    for name in files:
        print(agents_dir / name)


def install_claude(claude_home):
    """Opt-in Claude Code destination: the skill plus the permission shells, all managed with hashes."""
    claude_home = Path(os.path.abspath(claude_home.expanduser()))
    files = claude_agent_files()
    check_agents(claude_home / "agents", files)
    install(claude_home / "skills/multi-agent-hub")
    write_agents(claude_home / "agents", files)


def install_codex_agents(codex_home):
    """Opt-in: only the generated Codex permission shells; never part of the default install."""
    codex_home = Path(os.path.abspath(codex_home.expanduser()))
    write_agents(codex_home / "agents", codex_agent_files())


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dest", type=Path, help="native skill directory (default: ~/.codex/skills/multi-agent-hub)")
    parser.add_argument("--claude", action="store_true",
                        help="opt in: install into the Claude Code user folder (skills/multi-agent-hub and agents/hub-*.md) instead of the Codex default")
    parser.add_argument("--claude-home", type=Path, help="Claude Code user folder for --claude (default: ~/.claude)")
    parser.add_argument("--codex-agents", action="store_true",
                        help="opt in: install only the Codex permission shells (agents/hub-*.toml); the skill itself is not installed")
    parser.add_argument("--codex-home", type=Path, help="Codex user folder for --codex-agents (default: ~/.codex)")
    args = parser.parse_args(argv)
    if (args.claude or args.codex_agents) and args.dest:
        parser.error("--claude and --codex-agents cannot be combined with --dest")
    if args.claude_home and not args.claude:
        parser.error("--claude-home requires --claude")
    if args.codex_home and not args.codex_agents:
        parser.error("--codex-home requires --codex-agents")
    try:
        if args.claude:
            install_claude(args.claude_home or Path.home() / ".claude")
        if args.codex_agents:
            install_codex_agents(args.codex_home or Path.home() / ".codex")
        if not args.claude and not args.codex_agents:
            install(args.dest or Path.home() / ".codex/skills/multi-agent-hub")
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
