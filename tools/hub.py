def now():
    return datetime.now(timezone.utc).isoformat()


def slug(value):
    if not re.fullmatch(r"[a-z0-9-]{1,60}", value):
        raise ValueError("invalid task, role or agent identifier")
    return value


def task_dir(task):
    root = records_root().resolve()
    path = root / slug(task)
    if not path.resolve().is_relative_to(root):
        raise ValueError("task path escapes working directory")
    checkpoint_path = record_path(path / "CHECKPOINT.md")
    if not checkpoint_path.is_file():
        raise ValueError("unknown task")
    return path


def write(path, text):
    path = record_path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(text.encode("utf-8") if isinstance(text, str) else text)
        os.replace(temporary, path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


@contextmanager
def task_lock(directory):
    directory = record_path(directory)
    path = directory / ".lock"
    record_path(path)
    deadline = time.monotonic() + 30
    while True:
        try:
            descriptor = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
            break
        except FileExistsError:
            if time.monotonic() >= deadline:
                raise ValueError("timed out waiting for task lock: " + str(path))
            time.sleep(0.05)
    try:
        os.close(descriptor)
        yield
    finally:
        path.unlink()


def cell(value):
    return str(value).replace("\r", " ").replace("\n", " ").replace("|", "&#124;")


def section(text, name, addition, replace=False):
    pattern = re.compile(r"(^## " + re.escape(name) + r"\s*\n)(.*?)(?=^## |\Z)", re.M | re.S | re.I)
    def update(match):
        body = "" if replace else match[2].rstrip() + "\n"
        return match[1] + body.lstrip("\n") + addition + "\n\n"
    result, count = pattern.subn(update, text)
    if not count:
        raise ValueError("unknown section: " + name)
    return result


def checkpoint(task, name, text, replace=False):
    directory = task_dir(task)
    with task_lock(directory):
        update_checkpoint(directory, name, text, replace)


def update_checkpoint(directory, name, text, replace=False):
    path = record_path(directory / "CHECKPOINT.md")
    content = section(read_record(path, encoding="utf-8"), name, "- " + text, replace)
    content = re.sub(r"^Updated: .*", "Updated: " + now(), content, flags=re.M)
    write(path, content)


def new_task(args):
    root = records_root().resolve()
    path = root / slug(args.task)
    if not path.resolve().is_relative_to(root):
        raise ValueError("task path escapes working directory")
    if path.exists():
        raise ValueError("task already exists")
    bodies = {"Objective": args.objective, "Approved scope": args.scope, "Current state": "Planning"}
    content = f"# Checkpoint: {args.task}\nUpdated: {now()}\nOrchestrator: {args.orchestrator}\n\n"
    content += "".join(f"## {name}\n{bodies.get(name, 'Unknown')}\n\n" for name in SECTIONS)
    write(path / "CHECKPOINT.md", content)
    (path / "agents").mkdir()
    exclude_records_locally()


def exclude_records_locally():
    """Portable mode: keep `.multi-agent-hub/` out of `git status` through the local info/exclude when writable."""
    if os.environ.get("HUB_PORTABLE") != "1" or records_root().name != ".multi-agent-hub":
        return
    try:
        project = records_root().parent
        git = next((parent / ".git" for parent in (project, *project.parents) if (parent / ".git").exists()), None)
        if git is None:
            return
        if git.is_file():  # worktree or submodule: ".git" holds "gitdir: <path>"
            line = git.read_text(encoding="utf-8").strip()
            if not line.startswith("gitdir:"):
                return
            git = (git.parent / line[7:].strip()).resolve()
            if not (git / "HEAD").is_file():  # a hostile gitdir must look like a real git directory
                return
            if (git / "commondir").is_file():
                git = (git / (git / "commondir").read_text(encoding="utf-8").strip()).resolve()
                if not ((git / "HEAD").is_file() and (git / "objects").is_dir()):
                    return
        exclude = git / "info/exclude"
        if exclude.is_symlink():
            return
        current = exclude.read_text(encoding="utf-8") if exclude.is_file() else ""
        if any(entry.strip() in (".multi-agent-hub", ".multi-agent-hub/", "/.multi-agent-hub", "/.multi-agent-hub/")
               for entry in current.splitlines()):
            return
        exclude.parent.mkdir(parents=True, exist_ok=True)
        separator = "" if not current or current.endswith("\n") else "\n"
        exclude.write_text(current + separator + ".multi-agent-hub/\n", encoding="utf-8")
    except (OSError, ValueError):
        pass  # best effort: a read-only repository is not an error


def new_agent(args, kind=None):
    directory = record_path(task_dir(args.task) / "agents")
    role = slug(args.role)
    number = 1
    fields = {"Agent ID": "", "Role": role, "Task": args.task,
              "Assignment": args.assignment, "Parent orchestrator": args.parent,
              "Vendor": args.vendor, "Kind": kind or args.kind,
              "Requested model": args.model, "Actual model": "Unverified",
              "Requested effort": args.effort, "Actual effort": "Unverified",
              "Skills": args.skills or "none", "Status": "planned",
              "Session / run": "Unknown", "Resume id": "Unknown", "PID": "Unknown",
              "Worker status": "Unknown", "Created": now()}
    while True:
        agent_id = f"{role}-{number}"
        fields["Agent ID"] = agent_id
        content = f"# Agent {agent_id}\n| Field | Value |\n|---|---|\n"
        content += "".join(f"| {key} | {cell(value)} |\n" for key, value in fields.items())
        content += "\n## Progress\n\n## Result\n\n## Blockers\n"
        record_path(directory / (agent_id + ".md"))
        try:
            with (directory / (agent_id + ".md")).open("x", encoding="utf-8") as stream:
                stream.write(content)
            return agent_id
        except FileExistsError:
            number += 1


def agent_fields(path):
    return dict(re.findall(r"^\| ([^|]+) \| (.*?) \|$", read_record(path, encoding="utf-8"), re.M))


def update_agent(task, agent_id, fields=None, entries=None, preserve_cancelled=False):
    directory = task_dir(task)
    path = record_path(directory / "agents" / (slug(agent_id) + ".md"))
    with task_lock(directory):
        if not path.is_file():
            raise ValueError("unknown agent")
        content = read_record(path, encoding="utf-8")
        if preserve_cancelled and agent_fields(path).get("Status") == "cancelled":
            return False
        write_agent(path, content, fields, entries)
    return True


def write_agent(path, content, fields=None, entries=None):
    for key, value in (fields or {}).items():
        pattern = r"^\| " + re.escape(key) + r" \| .* \|$"
        if re.search(pattern, content, re.M):
            content = re.sub(pattern, lambda m: f"| {key} | {cell(value)} |", content, flags=re.M)
        else:
            content = content.replace("\n\n## Progress", f"\n| {key} | {cell(value)} |\n\n## Progress", 1)
    for name, value in (entries or {}).items():
        content = section(content, name, f"- {now()} {value}")
    write(path, content)


def session_path(path):
    """Read-only access to a Codex rollout: allowed only under the Codex session root, never for records."""
    path = Path(path)
    root = codex_session_dir().resolve()
    if not path.resolve().is_relative_to(root):
        raise ValueError("session path escapes the Codex session root")
    return path


def events(path, offset=0, session=False):
    path = session_path(path) if session else record_path(path)
    with path.open("rb") as stream:
        stream.seek(offset)
        text = stream.read().decode("utf-8-sig")
    for line in text.splitlines():
        try:
            value = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(value, dict):
            yield value


def distinct(values):
    return list(dict.fromkeys(v for v in values if isinstance(v, str) and v))


def codex_session_dir():
    return Path(os.environ.get("HUB_CODEX_SESSIONS", str(Path.home() / ".codex/sessions")))


def is_windows():
    return os.name == "nt"


def verify(vendor, event_path, rollout_offsets=None):
    data = list(events(event_path))
    models, efforts, session, tokens, result, resume_id = [], [], "Unknown", "Unknown", "", "Unknown"
    if vendor == "codex":
        thread = next((e.get("thread_id") for e in data if e.get("type") == "thread.started"), None)
        resume_id = thread if isinstance(thread, str) and thread else "Unknown"
        directory = codex_session_dir()
        matches = sorted(p for p in directory.rglob("rollout-*.jsonl")
                         if isinstance(thread, str) and thread and p.name.endswith(thread + ".jsonl")) if thread else []
        if matches:
            session = matches[-1].name
            for event in events(matches[-1], (rollout_offsets or {}).get(matches[-1], 0), session=True):
                payload = event.get("payload") or {}
                if event.get("type") == "turn_context":
                    models.append(payload.get("model"))
                    efforts.append(payload.get("effort"))
                if payload.get("type") == "token_count":
                    tokens = ((payload.get("info") or {}).get("total_token_usage") or {}).get("total_tokens", "Unknown")
    else:
        for event in data:
            if event.get("type") == "system" and event.get("subtype") == "init":
                models.append(event.get("model"))
                session = event.get("session_id") or "Unknown"
                resume_id = session
            if event.get("type") == "assistant":
                models.append((event.get("message") or {}).get("model"))
            if event.get("type") == "result":
                result = event.get("result") or ""
    return distinct(models), distinct(efforts), session, tokens, result, resume_id


def validate_route(args):
    catalog = tomllib.loads(model_catalog().read_text(encoding="utf-8"))[args.to]
    if args.model not in catalog["verified"]:
        return "model is unverified or unknown"
    premium = args.model in catalog["premium"] or args.effort in catalog["premium_efforts"]
    if premium and len((args.premium or "").strip()) < 10:
        return "premium route requires a reason of at least 10 characters"
    allowed = catalog["efforts"] + (catalog["premium_efforts"] if args.premium and len(args.premium.strip()) >= 10 else [])
    if args.effort not in allowed:
        return "unsupported effort"
    if len(args.reason.strip()) < 10:
        return "reason must contain at least 10 characters"
    return None


def delegate(args):
    if args.write and not args.cwd:
        print("REFUSED: --write requires explicit --cwd")
        return 2
    refusal = validate_route(args)
    if refusal:
        print("REFUSED: " + refusal)
        return 2
    directory = task_dir(args.task) / "agents"
    resume_id = None
    if args.resume:
        try:
            previous = directory / (slug(args.resume) + ".md")
        except ValueError:
            print("REFUSED: invalid resume agent identifier")
            return 2
        previous = record_path(previous)
        fields = agent_fields(previous) if previous.is_file() else {}
        if fields.get("Task") != args.task or fields.get("Vendor") != args.to:
            print("REFUSED: resume requires an agent from the same task and vendor")
            return 2
        resume_id = fields.get("Resume id")
        if not resume_id or resume_id in ("Unknown", "Unverified"):
            print("REFUSED: agent has no Resume id")
            return 2
    brief = Path(args.brief).read_text(encoding="utf-8")
    cwd = str(Path(args.cwd or work_root()).resolve())
    first = next((line.strip() for line in brief.splitlines() if line.strip()), "")
    args.vendor, args.assignment = args.to, f"brief {args.brief}: {first[:200]}"
    agent_id = new_agent(args, "delegated")
    update_agent(args.task, agent_id, {"Status": "running"}, {"Progress": "Route reason: " + args.reason + ("; Premium: " + args.premium if args.premium else "")})
    if args.resume:
        update_agent(args.task, agent_id, entries={"Progress": "Resumes " + args.resume})
    last = directory / (agent_id + ".last.md")
    event_path = directory / (agent_id + ".events.jsonl")
    models, efforts, session, observed_resume = [], [], "Unknown", "Unknown"
    blocker, result, tokens = "", "", "Unknown"
    process = None
    simulated = os.environ.get("HUB_SIMULATE_QUOTA") == args.to
    exe = shutil.which(args.to)
    if simulated:
        status, code, blocker = "quota-unavailable", 4, "simulated quota-unavailable"
    elif not exe:
        status, code, blocker = "failed", 1, "executable not found: " + args.to
    else:
        if args.to == "codex":
            sandbox = "workspace-write" if args.write else "read-only"
            argv = ([exe, "exec", "resume", resume_id, "--json"] if resume_id else
                    [exe, "exec", "--json", "-C", cwd, "-s", sandbox])
            argv += ["-m", args.model, "-c", f"model_reasoning_effort={args.effort}"]
            if resume_id:
                argv += ["-c", f'sandbox_mode="{sandbox}"']
            argv += ["-o", str(last), "-"]
        else:
            argv = [exe, "-p", "--model", args.model, "--effort", args.effort, "--output-format", "stream-json", "--verbose",
                    "--add-dir", str(directory.parent.resolve())]  # the task folder holds the shared checkpoint
            argv += (["--permission-mode", "acceptEdits", "--allowedTools", "Read,Edit,Write,Glob,Grep" + (",Bash" if args.allow_shell else "")]
                     if args.write else ["--allowedTools", "Read,Glob,Grep"])
            if resume_id:
                argv += ["--resume", resume_id]
        prompt = f"You are a worker agent delegated by the {args.parent} orchestrator for task {args.task}. Stay inside the assignment and the working directory. Report what you changed and the evidence. If blocked, say so; do not guess.\nTask checkpoint (shared state, read it when the brief refers to it or you need context): {(directory.parent / 'CHECKPOINT.md').resolve()}\n\n" + brief
        try:
            timed_out = False
            kill_failure = ""
            rollout_offsets = {path: path.stat().st_size for path in codex_session_dir().rglob("rollout-*.jsonl")} if args.to == "codex" else {}
            child_env = os.environ.copy()
            for key in ("HUB_PORTABLE", "HUB_PROJECT_ROOT", "HUB_WORK_ROOT", "HUB_RECORDS_ROOT", "HUB_MODEL_CATALOG"):
                child_env.pop(key, None)
            if args.to == "codex" and is_windows():
                child_env.pop("CODEX_WINDOWS_REGISTERED_CORE", None)
            # Publish the PID while holding the same lock used by stop, so stop
            # cannot race process creation or the final status update.
            with task_lock(directory.parent):
                process = subprocess.Popen(argv, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                           text=True, encoding="utf-8", errors="replace", cwd=cwd,
                                           start_new_session=os.name != "nt", env=child_env)
                path = directory / (agent_id + ".md")
                write_agent(path, read_record(path, encoding="utf-8"), {"PID": process.pid})
            try:
                stdout, stderr = process.communicate(prompt, timeout=args.timeout * 60 if args.timeout else None)
            except subprocess.TimeoutExpired:
                timed_out = True
                try:
                    kill_tree(process.pid)
                except OSError as exc:
                    kill_failure = "; process tree termination failed: " + str(exc)
                    # Recover available output without hanging again on a worker
                    # that the OS refused to stop. Keep its PID until exit is proven.
                    try:
                        stdout, stderr = process.communicate(timeout=1)
                    except subprocess.TimeoutExpired as pending:
                        stdout, stderr = (value.decode("utf-8", errors="replace") if isinstance(value, bytes) else value or ""
                                          for value in (pending.output, pending.stderr))
                else:
                    stdout, stderr = process.communicate()
            write(event_path, stdout)
            models, efforts, session, tokens, result, observed_resume = verify(args.to, event_path, rollout_offsets)
            last = record_path(last)
            if args.to == "codex" and last.is_file():
                result = read_record(last, encoding="utf-8")
            quota = next((line[:300] for line in (stdout + "\n" + stderr).splitlines()
                          if re.search(r"usage limit|rate limit|quota|429|too many requests", line, re.I)), None)
            match = (models == [args.model] and efforts == [args.effort]) if args.to == "codex" else bool(models) and all(args.model in m for m in models)
            if timed_out:
                status, code, blocker = "failed", 1, f"timeout after {args.timeout:g} min" + kill_failure
            elif process.returncode and quota:
                status, code, blocker = "quota-unavailable", 4, quota
            elif process.returncode:
                status, code, blocker = "failed", 1, f"process exited {process.returncode}: {stderr[:300]}"
            elif not match:
                status, code, blocker = "failed", 3, "route mismatch or missing verification evidence"
            else:
                status, code = "done", 0
        except (OSError, ValueError) as exc:
            # Verification problems must end the record as failed, never leave it running.
            status, code, blocker = "failed", 1, str(exc)
    event_path = record_path(event_path)
    last = record_path(last)
    if not event_path.exists():
        write(event_path, "")
    if args.to == "claude" or not last.exists():
        write(last, result or "Unknown\n")
    actual_model, actual_effort = ", ".join(models) or "Unverified", ", ".join(efforts) or "Unverified"
    # Whole value is a status word, optionally followed by " - ..." / " | ..." (the brief CONTRACT's one-line reply).
    reported = re.findall(r"^\**STATUS:\**[ \t]*(DONE_WITH_CONCERNS|NEEDS_CONTEXT|BLOCKED|DONE)\**(?:[ \t]+[-|–—][ \t].*)?[ \t]*\r?$", result, re.M | re.I)
    worker_status = reported[-1].upper() if reported else "Unknown"
    if status == "done" and worker_status in ("BLOCKED", "NEEDS_CONTEXT"):
        status, code, blocker = "blocked", 6, "worker reported " + worker_status
    entries = {"Result": (result[:2000] or "Unknown") + f"\n\nArtifact: {last}", "Progress": f"Total tokens: {tokens}"}
    if status == "done" and worker_status == "DONE_WITH_CONCERNS":
        entries["Progress"] += "\nworker reported DONE_WITH_CONCERNS"
    if blocker:
        entries["Blockers"] = blocker
    pid = process.pid if process is not None and process.poll() is None else "Unknown"
    updated = update_agent(args.task, agent_id, {"Status": status, "PID": pid, "Actual model": actual_model,
                           "Actual effort": actual_effort, "Session / run": session,
                           "Resume id": observed_resume, "Worker status": worker_status}, entries, preserve_cancelled=True)
    if not updated:
        status, code = "cancelled", 1
    print(json.dumps(dict(id=agent_id, status=status, requested_model=args.model, actual_model=actual_model,
                          actual_effort=actual_effort, session=session, worker_status=worker_status, exit=code)))
    return code


def kill_tree(pid):
    if os.name == "nt":
        result = subprocess.run(["taskkill", "/T", "/F", "/PID", str(pid)], capture_output=True, text=True)
        if result.returncode:
            raise OSError(result.stderr.strip() or result.stdout.strip())
    else:
        os.killpg(pid, signal.SIGKILL)


def stop(args):
    directory = task_dir(args.task)
    path = record_path(directory / "agents" / (slug(args.id) + ".md"))
    with task_lock(directory):
        fields = agent_fields(path)
        pid = fields.get("PID", "")
        if fields.get("Status") != "running" or not pid.isdecimal() or int(pid) <= 0:
            raise ValueError("agent is not running with a PID")
        kill_tree(int(pid))
        write_agent(path, read_record(path, encoding="utf-8"), {"Status": "cancelled", "PID": "Unknown"},
                    {"Blockers": "stopped by orchestrator"})


SECRET_PATTERNS = [
    r"\bsk-[A-Za-z0-9_-]{16,}", r"\bgh[pousr]_[A-Za-z0-9]{20,}", r"\bgithub_pat_[A-Za-z0-9_]{20,}",
    r"\bAKIA[0-9A-Z]{16}\b", r"\bxox[abprs]-[A-Za-z0-9-]{10,}", r"-----BEGIN [A-Z ]*PRIVATE KEY-----",
    r"\beyJ[A-Za-z0-9_-]{8,}\.eyJ[A-Za-z0-9_-]{8,}\.",
    r"(?i)\bbearer\s+[A-Za-z0-9._~+/-]{20,}",
    # NAME=value (any non-*** value) or NAME: value (6+ chars with a digit or symbol); NAME may carry a prefix such as
    # DB_PASSWORD or client_secret. Prose such as "secret: see vault" or "token: 150k used" stays allowed.
    r"(?i)(?<![A-Za-z0-9])(?:[A-Za-z0-9]+_)*(?:password|passwd|secret|token|api[_-]?key)(?![A-Za-z0-9])\s*"
    r"(?:=\s*(?!\*+(?:\s|$))\S+|:\s*(?!\*+(?:\s|$))(?=\S*[0-9!@#$%^&+/])\S{6,})",
]


def looks_secret(text):
    """Known secret shapes only; a guard against pasting one into the log, not a scanner."""
    return any(re.search(pattern, text) for pattern in SECRET_PATTERNS)


def work_log(args):
    timestamp = datetime.now(timezone.utc)
    day = timestamp.date().isoformat() if args.show in (None, "") else args.show
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", day):
        raise ValueError("log day must be YYYY-MM-DD")
    directory = record_path(records_root() / "log")
    path = record_path(directory / (day + ".md"))
    if args.show is not None:
        if args.kind or args.text is not None or args.task:
            raise ValueError("--show cannot be combined with a log entry")
        if path.is_file():
            print(read_record(path, encoding="utf-8"), end="")
        return
    if not args.kind or args.text is None:
        raise ValueError("log entry requires kind and --text")
    if looks_secret(args.text) or looks_secret(args.task or ""):
        raise ValueError("log text looks like it contains a secret; write *** instead (nothing was written)")
    task = "[" + slug(args.task) + "] " if args.task else ""
    line = f"- {timestamp:%H:%M:%SZ} {args.kind}: {task}{' '.join(args.text.splitlines())}\n"
    directory.mkdir(parents=True, exist_ok=True)
    with task_lock(directory):
        content = read_record(path, encoding="utf-8") if path.exists() else ""
        write(path, content + line)


def positive_minutes(value):
    minutes = float(value)
    if not math.isfinite(minutes) or minutes <= 0:
        raise argparse.ArgumentTypeError("timeout must be a finite number greater than zero")
    return minutes


def attempt(args):
    directory = task_dir(args.task)
    normalized = re.sub(r"\d", "#", " ".join((args.action + "\n" + args.outcome).lower().split()))
    fingerprint = hashlib.sha256(normalized.encode()).hexdigest()
    path = record_path(directory / "attempts.jsonl")
    with task_lock(directory):
        previous = sum(e.get("fingerprint") == fingerprint for e in events(path)) if path.exists() else 0
        content = read_record(path, encoding="utf-8") if path.exists() else ""
        content += json.dumps(dict(at=now(), fingerprint=fingerprint, action=args.action, outcome=args.outcome)) + "\n"
        write(path, content)
        update_checkpoint(directory, "Failures and attempted approaches", f"{now()} action: {args.action} | outcome: {args.outcome}")
    if previous:
        print(f"NO PROGRESS: same action and outcome seen {previous + 1} times; change approach or escalate")
        return 5
    return 0


def status(args):
    directories = [task_dir(args.task)] if args.task else sorted(records_root().glob("*/"))
    keys = ["Agent ID", "Role", "Skills", "Vendor", "Kind", "Requested model", "Actual model", "Requested effort", "Actual effort", "Status"]
    for directory in directories:
        record_path(directory)
        checkpoint_path = record_path(directory / "CHECKPOINT.md")
        if not checkpoint_path.is_file():
            continue
        content = read_record(checkpoint_path, encoding="utf-8")
        state = re.search(r"^## Current state\n(.*?)(?=^## |\Z)", content, re.M | re.S)
        print(f"\nTask: {directory.name}\nCurrent state: " + (state[1].strip() if state else "Unknown"))
        print("| " + " | ".join(keys) + " |\n|" + "---|" * len(keys))
        agents_dir = record_path(directory / "agents")
        for path in sorted(agents_dir.glob("*.md")):
            fields = dict(re.findall(r"^\| ([^|]+) \| (.*?) \|$", read_record(path, encoding="utf-8"), re.M))
            if "Agent ID" in fields:
                print("| " + " | ".join(fields.get(k, "Unknown") for k in keys) + " |")


def sync(args):
    if os.environ.get("HUB_PORTABLE") == "1":
        raise ValueError("sync is unavailable in portable mode")
    from hub_skills import local_skill_dirs
    local = local_skill_dirs(work_root())
    expected = {}
    for source in sorted((work_root() / "agents/shells").glob("*.md")):
        if source.name.lower() == "readme.md":
            continue
        text = source.read_text(encoding="utf-8")
        match = re.match(r"\A---\s*\n(.*?)\n---[^\n]*\n?(.*)\Z", text, re.S)
        if not match:
            raise ValueError("missing frontmatter: " + str(source))
        meta = {}
        for line in match[1].splitlines():
            if ":" in line:
                key, value = line.split(":", 1)
                meta[key.strip()] = value.strip().strip("\"'")
        if meta.get("native", "true").lower() == "false":
            continue
        name = slug(meta["name"])
        sandbox = meta.get("sandbox", "read-only")
        if sandbox not in ("read-only", "workspace-write"):
            raise ValueError("invalid sandbox")
        body = match[2].rstrip() + "\n"
        marker = MARKER + source.relative_to(ROOT).as_posix() + "; edit the source"
        front = "---\nname: " + json.dumps(name) + "\ndescription: " + json.dumps(meta["description"])
        if meta.get("tools"):
            front += "\ntools: " + meta["tools"]
        expected[ROOT / ".claude/agents" / (name + ".md")] = (front + "\n---\n<!-- " + marker + " -->\n" + body).encode()
        if "'''" in body:
            raise ValueError("TOML literal delimiter in shell body")
        expected[ROOT / ".codex/agents" / (name + ".toml")] = ("# " + marker + "\nname = " + json.dumps(name) + "\ndescription = " + json.dumps(meta["description"]) + "\nsandbox_mode = " + json.dumps(sandbox) + "\ndeveloper_instructions = '''\n" + body + "'''\n").encode()
    for directory in sorted((ROOT / "skills").glob("*/")):
        for source in sorted(directory.rglob("*")):
            if source.is_file():
                relative = source.relative_to(ROOT).as_posix()
                data = source.read_bytes()
                marker = MARKER + relative + "; edit the source"
                # Comments remain valid for the common skill text formats; binary assets are copied exactly.
                try:
                    data.decode("utf-8")
                    text = data.decode("utf-8")
                    if source.suffix in (".py", ".toml", ".yaml", ".yml", ".sh"):
                        text = "# " + marker + "\n" + text
                    else:
                        front = re.match(r"\A---\s*\n.*?\n---[^\n]*\n", text, re.S)
                        cut = front.end() if front else 0  # frontmatter stays first, where the CLIs read it
                        text = text[:cut] + "<!-- " + marker + " -->\n" + text[cut:]
                    data = text.encode()
                except UnicodeDecodeError:
                    pass
                for target in (".claude", ".agents"):
                    expected[ROOT / target / relative] = data
    drift, conflicts = [], []
    for path, data in expected.items():
        if any(path.is_relative_to(directory) for directory in local):
            drift.append(path)
            conflicts.append(path)
            continue
        # git may check files out with CRLF on Windows; line endings alone are not drift
        if not path.exists() or path.read_bytes().replace(b"\r\n", b"\n") != data.replace(b"\r\n", b"\n"):
            drift.append(path)
            if path.exists() and MARKER.encode() not in path.read_bytes()[:4096]:
                conflicts.append(path)
            elif not args.check:
                write(path, data)
    for target in (".claude/agents", ".codex/agents", ".claude/skills", ".agents/skills"):
        for path in (ROOT / target).rglob("*"):
            if (path.is_file() and path not in expected
                    and not any(path.is_relative_to(directory) for directory in local)
                    and MARKER.encode() in path.read_bytes()[:4096]):
                drift.append(path)
                if not args.check:
                    path.unlink()
    for path in sorted(drift):
        print(("CONFLICT: " if path in conflicts else "") + path.relative_to(ROOT).as_posix())
    for directory in local:
        print("LOCAL SKILL: " + directory.relative_to(ROOT).as_posix())
    return 1 if conflicts or (args.check and drift) else 0


def parser():
    cli = argparse.ArgumentParser(description=__doc__)
    commands = cli.add_subparsers(dest="command", required=True)
    task = commands.add_parser("task").add_subparsers(dest="operation", required=True).add_parser("new")
    task.add_argument("task")
    for flag in ("objective", "scope", "orchestrator"):
        task.add_argument("--" + flag, required=True, **({"choices": ["claude", "codex"]} if flag == "orchestrator" else {}))
    cp = commands.add_parser("checkpoint")
    cp.add_argument("task")
    cp.add_argument("--section", required=True)
    cp.add_argument("--text", required=True)
    cp.add_argument("--replace", action="store_true")
    agent = commands.add_parser("agent").add_subparsers(dest="operation", required=True)
    new = agent.add_parser("new")
    new.add_argument("task")
    for flag in ("role", "vendor", "model", "effort", "assignment", "parent"):
        new.add_argument("--" + flag, required=True, **({"choices": ["claude", "codex"]} if flag == "vendor" else {}))
    new.add_argument("--skills")
    new.add_argument("--kind", choices=["native", "delegated"], default="native")
    update = agent.add_parser("update")
    update.add_argument("task")
    update.add_argument("id")
    for flag in ("status", "actual-model", "actual-effort", "session", "progress", "result", "blocker"):
        update.add_argument("--" + flag, **({"choices": STATUSES} if flag == "status" else {}))
    run = commands.add_parser("delegate")
    run.add_argument("task")
    for flag in ("to", "role", "model", "effort", "brief", "reason", "parent"):
        run.add_argument("--" + flag, required=True, **({"choices": ["claude", "codex"]} if flag == "to" else {}))
    for flag in ("cwd", "premium", "skills"):
        run.add_argument("--" + flag)
    for flag in ("write", "allow-shell"):
        run.add_argument("--" + flag, action="store_true")
    run.add_argument("--resume")
    run.add_argument("--timeout", type=positive_minutes)
    cancel = commands.add_parser("stop")
    cancel.add_argument("task")
    cancel.add_argument("id")
    log = commands.add_parser("log")
    log.add_argument("kind", nargs="?", choices=["outcome", "decision", "feedback", "context"])
    log.add_argument("--text")
    log.add_argument("--task")
    log.add_argument("--show", nargs="?", const="")
    tried = commands.add_parser("attempt")
    tried.add_argument("task")
    tried.add_argument("--action", required=True)
    tried.add_argument("--outcome", required=True)
    state = commands.add_parser("status")
    state.add_argument("task", nargs="?")
    sync_cli = commands.add_parser("sync")
    sync_cli.add_argument("--check", action="store_true")
    skills_cli = commands.add_parser("skills", help="Index installed skills or install approved local sources")
    skills_cli.add_argument("operation", nargs="?", choices=["install"])
    return cli


def main(argv=None):
    args = parser().parse_args(argv)
    try:
        if args.command == "task":
            new_task(args)
        elif args.command == "checkpoint":
            checkpoint(args.task, args.section, args.text, args.replace)
        elif args.command == "agent":
            if args.operation == "new":
                print(new_agent(args))
            else:
                fields = {key: getattr(args, attr) for key, attr in [("Status", "status"), ("Actual model", "actual_model"), ("Actual effort", "actual_effort"), ("Session / run", "session")] if getattr(args, attr) is not None}
                entries = {key: getattr(args, attr) for key, attr in [("Progress", "progress"), ("Result", "result"), ("Blockers", "blocker")] if getattr(args, attr) is not None}
                update_agent(args.task, args.id, fields, entries)
        elif args.command == "delegate":
            return delegate(args)
        elif args.command == "stop":
            stop(args)
        elif args.command == "log":
            work_log(args)
        elif args.command == "attempt":
            return attempt(args)
        elif args.command == "status":
            status(args)
        elif args.command == "sync":
            return sync(args)
        elif args.command == "skills":
            from hub_skills import install_skills, index_skills
            if args.operation == "install" and os.environ.get("HUB_PORTABLE") == "1":
                raise ValueError("third-party skill installation is unavailable in portable mode")
            return install_skills(work_root()) if args.operation == "install" else index_skills(work_root(), destination=records_root() / "skills-index.md")
    except (ValueError, OSError, KeyError, tomllib.TOMLDecodeError) as exc:
        print("ERROR: " + str(exc))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
